// Build step 1 of 2 (step 2 is `vite build`). Reads the snapshot and writes everything static that
// is derived from it into public/:
//   data/**.json   per-route slices (src/lib/slices.ts, the same code the pre-render uses)
//   sitemap.xml    every public URL
//   rss.xml        blog feed
//   _redirects     Cloudflare Pages rules: API proxy, SPA shell, old handles/slugs
//   version.json   what is deployed, for the dashboard's "Is my change live?"
// Run: pnpm slices   (SITE_URL overrides the canonical origin)
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { allPaths, allSlices } from "../src/lib/slices";
import { loadSnapshot, snapshotFile } from "../src/lib/snapshot.server";
import { SITE_URL } from "../src/lib/site";

const root = process.cwd();
const pub = join(root, "public");
const snap = loadSnapshot(root);

function write(path: string, body: string) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body);
}

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// 1. Slices
rmSync(join(pub, "data"), { recursive: true, force: true });
const sliceMap = allSlices(snap);
for (const [name, value] of sliceMap) write(join(pub, "data", `${name}.json`), JSON.stringify(value));

// 2. Sitemap
const lastmod = snap.version.contentChangedAt.slice(0, 10);
write(
  join(pub, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${allPaths(snap)
    .map((p) => `  <url><loc>${esc(SITE_URL + p)}</loc><lastmod>${lastmod}</lastmod></url>`)
    .join("\n")}\n</urlset>\n`,
);

// 3. RSS
const people = new Map(snap.people.map((p) => [p.handle, p.name]));
const items = snap.posts
  .map(
    (p) => `    <item>
      <title>${esc(p.title)}</title>
      <link>${SITE_URL}/blog/${p.slug}</link>
      <guid isPermaLink="true">${SITE_URL}/blog/${p.slug}</guid>
      <pubDate>${new Date(p.publishedAt).toUTCString()}</pubDate>
      <dc:creator>${esc(people.get(p.author) ?? p.author)}</dc:creator>
${p.tags.map((t) => `      <category>${esc(t)}</category>`).join("\n")}
      <description>${esc(p.excerpt)}</description>
      <content:encoded><![CDATA[${p.bodyHtml.replace(/]]>/g, "]]]]><![CDATA[>")}]]></content:encoded>
    </item>`,
  )
  .join("\n");
write(
  join(pub, "rss.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:content="http://purl.org/rss/1.0/modules/content/" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${esc(snap.club.name)} blog</title>
    <link>${SITE_URL}/blog</link>
    <atom:link href="${SITE_URL}/rss.xml" rel="self" type="application/rss+xml" />
    <description>${esc(snap.club.tagline)}</description>
    <language>en</language>
    <lastBuildDate>${new Date(snap.version.builtAt).toUTCString()}</lastBuildDate>
${items}
  </channel>
</rss>
`,
);

// 4. _redirects (Cloudflare Pages: first match wins; Functions take /api/* before these rules apply)
const redirects = [
  "# Generated by scripts/slices.ts. Do not edit; change the snapshot or the script.",
  "# /api/*  -> functions/api/[[path]].ts. Pages Functions match before these rules (see _routes.json),",
  "#            so the API proxy needs no line here.",
  "# The SPA shell is dist/client/_shell.html; Pages serves it at /_shell (a rewrite to /_shell.html would 308).",
  "/dashboard  /_shell  200",
  "/dashboard/*  /_shell  200",
  "/login  /_shell  200",
  ...snap.redirects.map((r) => `${r.from}  ${r.to}  301`),
];
write(join(pub, "_redirects"), redirects.join("\n") + "\n");

// Only /api/* invokes the Pages Function; everything else is served as a static asset.
write(join(pub, "_routes.json"), JSON.stringify({ version: 1, include: ["/api/*"], exclude: [] }));

// 5. version.json
write(join(pub, "version.json"), JSON.stringify(snap.version));

console.log(
  `slices: ${sliceMap.size} slices, ${allPaths(snap).length} urls, ${snap.redirects.length} redirects from ${relative(root, snapshotFile(root))}`,
);
